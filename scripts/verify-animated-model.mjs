import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'public/models/manifest.json'), 'utf8'));
assert.equal(manifest.version, 3);
assert.equal(manifest.assets.length, 1, 'One shared garment base asset');
const asset = manifest.assets[0];
assert.equal(asset.path, '/models/cloud-animated.glb');
assert.deepEqual(asset.variants, ['cloud', 'reference']);
const bytes = fs.readFileSync(path.join(root, 'public', asset.path));
assert.equal(bytes.length, asset.bytes);
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), asset.sha256);
assert.equal(bytes.readUInt32LE(0), 0x46546c67, 'GLB magic');
assert.equal(bytes.readUInt32LE(4), 2, 'glTF 2');
assert.equal(bytes.readUInt32LE(8), bytes.length, 'GLB declared length');
const jsonLength = bytes.readUInt32LE(12);
assert.equal(bytes.readUInt32LE(16), 0x4e4f534a, 'JSON chunk');
const gltf = JSON.parse(bytes.subarray(20, 20 + jsonLength).toString('utf8'));
const active = new Set();
function visit(index) { if (active.has(index)) return; active.add(index); for (const child of gltf.nodes[index].children || []) visit(child); }
for (const index of gltf.scenes[gltf.scene || 0].nodes) visit(index);
const nodes = [...active].map(i => gltf.nodes[i]);
assert.equal(nodes.filter(n => n.mesh !== undefined).length, asset.activeMeshCount);
assert.equal(asset.activeMeshCount, 40);
assert(nodes.some(n => /sleeve/i.test(n.name)), 'Sleeves present');
assert(nodes.some(n => /body/i.test(n.name)), 'Shirt body present');
assert(!nodes.some(n => /wear-patch|wear-thread|label-print/i.test(n.name)), 'No invented damage or composition label');
assert(!gltf.animations?.length, 'Motion is generated by the runtime physics and choreography');
assert(!gltf.buffers.some(b => b.uri), 'Binary geometry stays local in the GLB');
assert(!gltf.images?.some(i => i.uri), 'No external model texture dependency');
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
assert.equal(packageJson.dependencies.three, '0.180.0');
assert.deepEqual(fs.readdirSync(path.join(root, 'public/models')).filter(n => n.endsWith('.glb')), ['cloud-animated.glb']);
console.log(JSON.stringify({ status: 'passed', baseModels: 1, variants: asset.variants, activeMeshes: asset.activeMeshCount, bytes: asset.bytes, sha256: asset.sha256, checks: ['GLB structure', 'local geometry', 'manifest byte length and hash', 'single shared model', 'no invented wear or fibre label', 'pinned Three.js'] }, null, 2));
